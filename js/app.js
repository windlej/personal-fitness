  /* ------------------------------------------------------- progress view */
  function renderProgress() {
    var today = todayISO();
    var startISO = ANCHOR <= today ? ANCHOR : weekStart(today);
    var done = 0, mod = 0, skipped = 0, totalDist = 0, totalTime = 0, rpeSum = 0, rpeN = 0, trainable = 0;
    for (var iso = startISO; iso <= today; iso = addDays(iso, 1)) {
      var day = dayFor(iso);
      if (!isTrainable(day)) continue;
      trainable++;
      var l = logFor(iso);
      if (!l) continue;
      if (l.status === "done") done++;
      else if (l.status === "modified") mod++;
      else if (l.status === "skipped") skipped++;
      if (l.distance) totalDist += +l.distance;
      if (l.duration) totalTime += +l.duration;
      if (l.rpe) { rpeSum += +l.rpe; rpeN++; }
    }
    var completed = done + mod;
    var completion = trainable ? Math.round((completed / trainable) * 100) : 0;

    var html = '<div class="card"><div class="section-head"><h3 class="card-title">Progress since ' + esc(fmtShort(startISO)) + "</h3>" +
      '<span class="chip">' + esc(weekLabel(today)) + "</span></div>";
    html += '<div class="stat-grid">' +
      stat(completion + "%", "Completion", completed + "/" + trainable + " trainable") +
      stat(done + mod, "Sessions logged", skipped ? skipped + " skipped" : "on track") +
      stat(fmtMin(Math.round(totalTime)), "Time logged", "all sessions") +
      stat(totalDist.toFixed(1) + " " + store.settings.unit, "Distance logged", rpeN ? "avg RPE " + (rpeSum / rpeN).toFixed(1) : "") +
      "</div>";
    if (trainable) {
      html += '<div class="hr" style="margin:16px 0"></div><div class="bars">' +
        progressBar("Completed", completed, trainable, "var(--z2)") +
        progressBar("Skipped", skipped, trainable, "var(--z5)") +
        progressBar("Not logged", trainable - completed - skipped, trainable, "var(--border)") + "</div>";
    }
    html += "</div>";

    html += renderWeeklyVolume(today);
    html += renderRpeTrend();
    html += renderAdherence(startISO, today);
    document.getElementById("app").innerHTML = html;
  }
