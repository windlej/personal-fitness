  function exportCSV() {
    var cols = ["date", "weekday", "week", "phase", "session", "status", "duration_min", "distance", "pace", "rpe", "feel", "notes"];
    var lines = [cols.join(",")];
    Object.keys(store.logs).sort().forEach(function (iso) {
      var l = store.logs[iso];
      var d = findDay(iso);
      var row = [
        iso,
        d ? d.weekday : "",
        d ? d.week : "",
        d ? d.phase : "",
        d ? d.session : "",
        l.status || "",
        l.duration != null ? l.duration : "",
        l.distance != null ? l.distance : "",
        paceStr(l.duration, l.distance),
        l.rpe != null ? l.rpe : "",
        feelLabel(l.feel || "") || "",
        l.notes || "",
      ].map(csvCell).join(",");
      lines.push(row);
    });
    download("training-log-" + todayISO() + ".csv", lines.join("\n"), "text/csv");
    toast("Exported CSV");
  }
  function csvCell(v) {
    v = v == null ? "" : String(v);
    if (/[",\n]/.test(v)) return '"' + v.replace(/"/g, '""') + '"';
    return v;
  }
  function download(filename, content, type) {
    var blob = new Blob([content], { type: type });
    var url = URL.createObjectURL(blob);
    var a = document.createElement("a");
    a.href = url; a.download = filename;
    document.body.appendChild(a); a.click(); a.remove();
    setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
  }
  function importJSON(file) {
    var reader = new FileReader();
    reader.onload = function () {
      try {
        var data = JSON.parse(reader.result);
        var logs = data.logs || data;
        var count = 0;
        Object.keys(logs).forEach(function (iso) {
          if (/^\d{4}-\d{2}-\d{2}$/.test(iso)) { store.logs[iso] = logs[iso]; count++; }
        });
        if (data.settings && data.settings.unit) store.settings.unit = data.settings.unit;
        save();
        closeModal();
        render();
        toast("Imported " + count + " entries");
      } catch (e) {
        toast("Could not read that file");
      }
    };
    reader.readAsText(file);
  }

