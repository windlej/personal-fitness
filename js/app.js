  function renderProgress() {
    beginView();
    var today = todayISO();
    var startISO = ANCHOR <= today ? ANCHOR : weekStart(today);
    var done = 0, mod = 0, skipped = 0, totalDist = 0, totalTime = 0, rpeSum = 0, rpeN = 0, trainable = 0;
    for (var iso = startISO; iso <= today; iso = addDays(iso, 1)) {
      var day = dayFor(iso);
      if (!isTrainable(day)) continue;
      trainable++;
      var l = logFor(iso);
      if (!l) continue;
      if (l.status === "done") done++;
      else if (l.status === "modified") mod++;
      else if (l.status === "skipped") skipped++;
      if (l.distance) totalDist += +l.distance;
      if (l.duration) totalTime += +l.duration;
      if (l.rpe) { rpeSum += +l.rpe; rpeN++; }
    }
    var completed = done + mod;
    var completion = trainable ? Math.round((completed / trainable) * 100) : 0;
    var notLogged = trainable - completed - skipped;

    var html = '<p class="view-note">since ' + esc(fmtShort(startISO)) + " · " + esc(weekLabel(today)) + "</p>";

    html += section("totals", facts([
      ["completion", '<span class="stat-v">' + completion + '%</span> <code class="bar tok--done">' + barMarkup(completed, trainable) + '</code> <span class="fact-note">' + completed + "/" + trainable + " trainable</span>"],
      ["sessions", '<span class="stat-v">' + (done + mod) + "</span> logged" + (skipped ? ' · <span class="tok tok--skipped">[!]</span> ' + skipped + " skipped" : " · none skipped")],
      ["time", '<span class="stat-v">' + esc(fmtMin(Math.round(totalTime)) || "0") + "</span> logged"],
      ["distance", '<span class="stat-v">' + totalDist.toFixed(1) + " " + esc(store.settings.unit) + "</span> logged" + (rpeN ? ' · <span class="fact-note">avg RPE ' + (rpeSum / rpeN).toFixed(1) + "</span>" : "")]
    ]));

    if (trainable) {
      html += section("split",
        '<div class="bars">' +
          barRow("completed", completed, trainable, "done") +
          barRow("skipped", skipped, trainable, "skipped") +
          barRow("not logged", notLogged, trainable, "dim") +
        "</div>");
    }

    var volume = renderWeeklyVolume(today);
    if (volume) html += section("volume", volume);

    var rpe = renderRpeTrend();
    if (rpe) html += section("rpe trend", rpe);

    var adherence = renderAdherence(startISO, today);
    if (adherence) html += section("adherence", adherence);

    document.getElementById("app").innerHTML = html;
  }
