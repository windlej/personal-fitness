  function renderWeeklyVolume(today) {
    var thisWeek = weekStart(today);
    var rows = [];
    for (var i = 11; i >= 0; i--) rows.push(addDays(thisWeek, -7 * i));
    var maxVal = 0;
    var data = rows.map(function (start) {
      var planned = 0, actual = 0;
      for (var j = 0; j < 7; j++) {
        planned += (dayFor(addDays(start, j)).runMin || 0);
        var l = logFor(addDays(start, j));
        if (l && l.duration) actual += +l.duration;
      }
      maxVal = Math.max(maxVal, planned, actual);
      return { start: start, planned: planned, actual: actual };
    });
    if (!maxVal) return "";
    var html = '<div class="card"><h3 class="card-title">Weekly volume — planned vs logged</h3><div class="bars" style="margin-top:12px">';
    data.forEach(function (r) {
      var pw = Math.round((r.planned / maxVal) * 100), aw = Math.round((r.actual / maxVal) * 100);
      html += '<div class="bar-row"><span class="muted">' + esc(fmtShort(r.start)) + "</span>" +
        '<span class="bar-track"><span class="bar-fill plan" style="width:' + pw + '%"></span>' +
        '<span class="bar-fill actual" style="width:' + aw + "%;margin-left:-" + aw + '%"></span></span>' +
        '<span class="bar-lbl">' + (r.actual ? fmtMin(r.actual) : "0") + "</span></div>";
    });
    html += '</div><div class="legend"><span><i style="background:var(--accent)"></i>Logged</span><span><i style="background:var(--border)"></i>Planned</span></div></div>';
    return html;
  }
