  function renderAdherence(past) {
    var kinds = {};
    past.forEach(function (d) {
      if (!isTrainable(d)) return;
      var k = d.kind;
      kinds[k] = kinds[k] || { planned: 0, done: 0 };
      kinds[k].planned++;
      var l = logFor(d.date);
      if (l && (l.status === "done" || l.status === "modified")) kinds[k].done++;
    });
    var label = { easy: "Easy", long: "Long run", threshold: "Threshold", vo2: "VO2", speed: "Speed", test: "Test/race", rest: "Rest/KB", other: "Other" };
    var keys = Object.keys(kinds).sort();
    if (!keys.length) return "";
    var html = '<div class="card"><h3 class="card-title">Adherence by session type</h3><div class="bars" style="margin-top:12px">';
    keys.forEach(function (k) {
      var it = kinds[k];
      var pct = it.planned ? Math.round((it.done / it.planned) * 100) : 0;
      html += progressBar(label[k] || k, it.done, it.planned, "var(--accent)");
    });
    html += "</div></div>";
    return html;
  }

