  // URL hash like #day=2027-01-01 or #week
  function applyHash() {
    var h = location.hash.replace(/^#/, "");
    if (!h) return;
    var parts = h.split("&");
    parts.forEach(function (p) {
      var kv = p.split("=");
      if (kv[0] === "day" && kv[1]) state.selectedDate = kv[1];
      if (["day", "week", "calendar", "journal", "progress", "plan"].indexOf(kv[0]) >= 0) state.view = kv[0];
    });
  }
