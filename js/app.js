  function setStatus(val) {
    var iso = state.selectedDate;
    var log = store.logs[iso] || {};
    if (log.status === val) return;
    log.status = val;
    log.updatedAt = new Date().toISOString();
    store.logs[iso] = log;
    save();
    renderDay();
  }
  function saveLog() {
    var iso = state.selectedDate;
    var log = store.logs[iso] || {};
    var fresh = collectLog();
    // keep status if already chosen, else default to done
    Object.keys(fresh).forEach(function (k) { log[k] = fresh[k]; });
    Object.keys(log).forEach(function (k) {
      if (k !== "status" && !(k in fresh) && k !== "updatedAt") delete log[k];
    });
    if (!log.status) log.status = "done";
    log.updatedAt = new Date().toISOString();
    store.logs[iso] = log;
    save();
    renderDay();
    toast("Saved");
  }
  function clearLog() {
    delete store.logs[state.selectedDate];
    save();
    renderDay();
    toast("Cleared");
  }
  function shiftMonth(n) {
    var base = state.calMonth || state.selectedDate.slice(0, 7);
    var y = +base.slice(0, 4), m = +base.slice(5, 7) - 1 + n;
    var d = new Date(y, m, 1);
    state.calMonth = d.getFullYear() + "-" + pad(d.getMonth() + 1);
    renderCalendar();
  }

